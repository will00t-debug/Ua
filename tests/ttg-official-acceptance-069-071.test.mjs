import test from 'node:test';
import assert from 'node:assert/strict';
import {TTG_BY_ID} from '../dist/ttg-builder.mjs';
import {newTtgCoreMatch,legalTtgCoreActions,dispatchTtgCoreAction,assertTtgCoreState} from '../dist/ttg-core-match.mjs';
import {withTtgDerivedEnergy} from '../dist/ttg-energy-snapshot.mjs';
import {canRed070ServeAsRaidBase,red071ImpactNull} from '../dist/ttg-red-tenth-three.mjs';
import {beginTtgLifeTrigger} from '../dist/ttg-green-life.mjs';
const counts=Object.fromEntries([...['042','043','045','046','047','051','053','054','064','069','070','071'].map(n=>['TTG-1-'+n,4]),['TTG-1-036',1],['TTG-1-038',1]]);
const game=seed=>{const s=newTtgCoreMatch({decks:[counts,counts],seed,first:0});s.phase='main';s.players[0].turnCount=2;s.players[0].apCards[1].ready=true;return s;};
const take=(p,id)=>{for(const z of ['hand','deck','life','outside']){const i=p[z].findIndex(c=>c.cardId===id);if(i>=0)return p[z].splice(i,1)[0]}throw Error('Missing '+id)};
const stage=(s,id,line='energy',slot=0,p=0)=>{const c=take(s.players[p],id);c.ready=true;s.players[p][line][slot]=c;return c};
const offered=(s,fn)=>{const a=legalTtgCoreActions(s).find(fn);assert.ok(a,'Missing legal action');return a};
test('069: real ACTIVE Leeron retires to OUTSIDE and recovers chosen printed Gunmen to hand, no AP consumed',()=>{
 let s=game(6901),p=s.players[0];const source=stage(s,'TTG-1-069'),gun=take(p,'TTG-1-071');
 p.outside.push(gun);s=withTtgDerivedEnergy(s,0);
 const ap=p.apCards.map(c=>c.ready),a=offered(s,x=>x.type==='ttgRed069Main'&&x.uid===source.uid&&x.recoverUid===gun.uid);
 s=dispatchTtgCoreAction(s,a);
 assert.equal(s.players[0].energy[0],null);
 assert.ok(s.players[0].outside.some(c=>c.uid===source.uid&&!c.ready));
 assert.ok(s.players[0].hand.some(c=>c.uid===gun.uid));
 assert.deepEqual(s.players[0].apCards.map(c=>c.ready),ap);
 assert.ok(assertTtgCoreState(s));
});
test('069 cannot activate without outside Gunmen, using REST source, or select non-Gunmen; no cost on reject',()=>{
 let s=game(6902),p=s.players[0],source=stage(s,'TTG-1-069');
 const wrong=take(p,'TTG-1-045');p.outside.push(wrong);
 s=withTtgDerivedEnergy(s,0);
 assert.ok(!legalTtgCoreActions(s).some(x=>x.type==='ttgRed069Main'));
 const real=take(p,'TTG-1-071');p.outside.push(real);
 s=withTtgDerivedEnergy(s,0);
 assert.ok(legalTtgCoreActions(s).some(x=>x.type==='ttgRed069Main'&&x.recoverUid===real.uid));
 const snapshot=JSON.stringify(s);
 assert.throws(()=>dispatchTtgCoreAction(s,{type:'ttgRed069Main',player:0,uid:source.uid,recoverUid:wrong.uid}),/Illegal|Unsupported/i);
 assert.equal(JSON.stringify(s),snapshot);
 s.players[0].energy[0].ready=false;
 assert.ok(!legalTtgCoreActions(s).some(x=>x.type==='ttgRed069Main'));
 assert.ok(assertTtgCoreState(s));
});
test('070: can substitute Raid base only when no own Kamina anywhere in field, including Raid base',()=>{
 let s=game(7001),rossiu=stage(s,'TTG-1-070');
 const gurren={cardId:'TTG-1-072',nameJa:'グレン',uid:'printed-raid'};
 assert.equal(canRed070ServeAsRaidBase(s,0,rossiu,gurren),true);
 const kamina=stage(s,'TTG-1-045','front',0);
 assert.equal(canRed070ServeAsRaidBase(s,0,rossiu,gurren),false);
 s.players[0].front[0]=null;s.players[0].outside.push(kamina);
 assert.equal(canRed070ServeAsRaidBase(s,0,rossiu,gurren),true);
 const raid=stage(s,'TTG-1-071','front',0),base=take(s.players[0],'TTG-1-046');
 raid.stack=[base];
 assert.equal(canRed070ServeAsRaidBase(s,0,rossiu,gurren),false);
 assert.equal(canRed070ServeAsRaidBase(s,1,rossiu,gurren),true,'enemy Kamina does not affect own condition');
 assert.ok(assertTtgCoreState(s));
});
test('070: printed DRAW life trigger is optional and does not reveal any non-trigger card',()=>{
 let s=game(7002),p=s.players[0],life=take(p,'TTG-1-070');p.deck.push(p.life.shift());p.life.unshift(life);
 s=withTtgDerivedEnergy(s,0);
 const q=beginTtgLifeTrigger(s,{player:0,lifeUid:life.uid}),top=q.players[0].deck[0].uid;
 assert.ok(legalTtgCoreActions(q).some(x=>x.mode==='draw'));
 assert.ok(legalTtgCoreActions(q).some(x=>x.mode==='decline'));
 const declined=dispatchTtgCoreAction(q,offered(q,x=>x.mode==='decline'));
 assert.equal(declined.players[0].deck[0].uid,top);
 const accepted=dispatchTtgCoreAction(q,offered(q,x=>x.mode==='draw'));
 assert.ok(accepted.players[0].hand.some(c=>c.uid===top));
 assert.ok(assertTtgCoreState(accepted));assert.ok(assertTtgCoreState(declined));
});
test('071: real 4-RED AP1 Raid onto Kittan preserves UID stack and enters ACTIVE',()=>{
 let s=game(7101),p=s.players[0],base=stage(s,'TTG-1-047','front',0),gen=stage(s,'TTG-1-042');
 gen.energyBonus=3;
 const card=take(p,'TTG-1-071');p.hand.push(card);
 s=withTtgDerivedEnergy(s,0);
 const a=offered(s,x=>x.type==='raidTtg'&&x.cardId==='TTG-1-071'&&x.baseUid===base.uid&&x.line==='front'&&x.slot===0);
 s=dispatchTtgCoreAction(s,{...a,payApUids:[s.players[0].apCards[0].uid]});
 assert.equal(s.players[0].front[0].uid,card.uid);
 assert.equal(s.players[0].front[0].stack[0].uid,base.uid);
 assert.equal(s.players[0].front[0].ready,true);
 assert.equal(s.players[0].apCards[0].ready,false);
 assert.equal(red071ImpactNull(s.players[0].front[0]),true);
 assert.ok(assertTtgCoreState(s));
});
